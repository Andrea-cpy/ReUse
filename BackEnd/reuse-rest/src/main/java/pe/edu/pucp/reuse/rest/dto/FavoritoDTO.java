package pe.edu.pucp.reuse.rest.dto;

public class FavoritoDTO {
    private int idFavorito;
    private String fechaGuardado;
    private int idUsuario;
    private int idAnuncio;
    private String tituloAnuncio;
    private double precioAnuncio;
    private String estadoAnuncio;

    public FavoritoDTO() {
    }

    public int getIdFavorito() {
        return idFavorito;
    }

    public void setIdFavorito(int idFavorito) {
        this.idFavorito = idFavorito;
    }

    public String getFechaGuardado() {
        return fechaGuardado;
    }

    public void setFechaGuardado(String fechaGuardado) {
        this.fechaGuardado = fechaGuardado;
    }

    public int getIdUsuario() {
        return idUsuario;
    }

    public void setIdUsuario(int idUsuario) {
        this.idUsuario = idUsuario;
    }

    public int getIdAnuncio() {
        return idAnuncio;
    }

    public void setIdAnuncio(int idAnuncio) {
        this.idAnuncio = idAnuncio;
    }

    public String getTituloAnuncio() {
        return tituloAnuncio;
    }

    public void setTituloAnuncio(String tituloAnuncio) {
        this.tituloAnuncio = tituloAnuncio;
    }

    public double getPrecioAnuncio() {
        return precioAnuncio;
    }

    public void setPrecioAnuncio(double precioAnuncio) {
        this.precioAnuncio = precioAnuncio;
    }

    public String getEstadoAnuncio() {
        return estadoAnuncio;
    }

    public void setEstadoAnuncio(String estadoAnuncio) {
        this.estadoAnuncio = estadoAnuncio;
    }
}
